#!/usr/bin/env node
/**
 * Generates seed listings for the Scraps board using xAI's Grok.
 *
 * WHY THIS IS A BUILD-TIME TOOL AND NOT A FEATURE
 *
 * The write path is SpacetimeDB reducers, and reducers must be
 * deterministic — no network, no filesystem, no wall clock. That is not an
 * inconvenience we are routing around: it is the same all-or-nothing property
 * that makes two simultaneous claims resolve to exactly one winner. A reducer
 * that could call an API could not offer that guarantee.
 *
 * So this runs on a laptop, before anything is published. It prints Rust that
 * a human reads, checks and pastes into `seed_listings()`. The running app has
 * no dependency on xAI, ships no API key, and behaves identically whether or
 * not this tool was ever used.
 *
 *   export XAI_API_KEY=...        # never commit this; .env is gitignored
 *   node tools/generate-listings.mjs 15 > /tmp/seed.rs
 *
 * Output is validated against the module's own rules before printing, because
 * `post_listing` rejects empty or over-long text and non-finite or
 * out-of-range coordinates. Better to fail here than to paste something the
 * database will refuse.
 */

const API = 'https://api.x.ai/v1/chat/completions'
const MODEL = process.env.XAI_MODEL ?? 'grok-4.6'

// Mirrors the constants in server/spacetimedb/src/lib.rs.
const MAX_DONOR = 80
const MAX_DESCRIPTION = 280
// Baltimore, loosely. Anything outside this is a hallucinated location.
const LAT = [39.19, 39.39]
const LNG = [-76.75, -76.5]

const count = Number(process.argv[2] ?? 15)
const key = process.env.XAI_API_KEY
if (!key) {
  console.error('XAI_API_KEY is not set.\n  export XAI_API_KEY=...')
  process.exit(1)
}

const prompt = `Generate exactly ${count} surplus-food listings for a food-rescue
board in Baltimore, Maryland.

Return ONLY a JSON array, no prose and no code fence. Each element:
  { "donor": string, "description": string, "hours": number,
    "lat": number, "lng": number }

Rules:
- donor: an INVENTED business name, at most ${MAX_DONOR} characters. Do not use
  the name of any real business — this is a public demo.
- description: what the food actually is, with a rough quantity. At most
  ${MAX_DESCRIPTION} characters. Concrete, not marketing copy.
- hours: 1 to 8, how long until the pickup window closes.
- lat/lng: a plausible point in a real Baltimore neighbourhood. lat between
  ${LAT[0]} and ${LAT[1]}, lng between ${LNG[0]} and ${LNG[1]}. Spread them
  across different neighbourhoods rather than clustering downtown.`

const res = await fetch(API, {
  method: 'POST',
  headers: { Authorization: `Bearer ${key}`, 'Content-Type': 'application/json' },
  body: JSON.stringify({
    model: MODEL,
    messages: [{ role: 'user', content: prompt }],
    temperature: 0.8,
  }),
})

if (!res.ok) {
  console.error(`xAI returned ${res.status}: ${await res.text()}`)
  process.exit(1)
}

const body = await res.json()
const text = body.choices?.[0]?.message?.content ?? ''

let rows
try {
  // Models sometimes fence the JSON despite being told not to.
  rows = JSON.parse(text.replace(/^```(?:json)?\s*|\s*```$/g, '').trim())
} catch {
  console.error('Could not parse the response as JSON. Raw output:\n' + text)
  process.exit(1)
}

/** The module will reject bad rows anyway; catching them here is cheaper. */
const problems = []
for (const [i, r] of rows.entries()) {
  const where = `row ${i} (${r?.donor ?? '?'})`
  if (!r?.donor?.trim()) problems.push(`${where}: donor empty`)
  else if ([...r.donor.trim()].length > MAX_DONOR) problems.push(`${where}: donor too long`)
  if (!r?.description?.trim()) problems.push(`${where}: description empty`)
  else if ([...r.description.trim()].length > MAX_DESCRIPTION)
    problems.push(`${where}: description too long`)
  if (!Number.isFinite(r?.lat) || r.lat < LAT[0] || r.lat > LAT[1])
    problems.push(`${where}: lat ${r?.lat} is not in Baltimore`)
  if (!Number.isFinite(r?.lng) || r.lng < LNG[0] || r.lng > LNG[1])
    problems.push(`${where}: lng ${r?.lng} is not in Baltimore`)
  if (!Number.isFinite(r?.hours) || r.hours < 1 || r.hours > 8)
    problems.push(`${where}: hours ${r?.hours} out of range`)
}

if (problems.length) {
  console.error(`${problems.length} row(s) failed validation:\n  ` + problems.join('\n  '))
  process.exit(1)
}

const esc = (s) => s.trim().replace(/\\/g, '\\\\').replace(/"/g, '\\"')

console.log(`// Generated by tools/generate-listings.mjs using xAI ${MODEL}.`)
console.log(`// ${rows.length} listings, validated against the module's own limits.`)
console.log(`// Read these before pasting — donor names must not be real businesses.`)
console.log(`const SEED: &[(&str, &str, i64, f64, f64)] = &[`)
for (const r of rows) {
  console.log(
    `    ("${esc(r.donor)}", "${esc(r.description)}", ${r.hours}, ${r.lat}, ${r.lng}),`,
  )
}
console.log(`];`)
